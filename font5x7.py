BLANK = (".....", ".....", ".....", ".....", ".....", ".....", ".....")


def glyph(char):
    """Return the 7-row bitmap for one character."""
    if "a" <= char <= "z":
        char = char.upper()
    # Typographic punctuation falls back to its plain ASCII lookalike
    # so quoted copy renders instead of leaving a blank cell.
    if char in ("\u201c", "\u201d"):
        char = '"'
    elif char in ("\u2018", "\u2019"):
        char = "'"
    elif char in ("\u2014", "\u2013"):
        char = "-"
    return GLYPHS.get(char, BLANK)


def text_width(text, scale):
    """Pixel width of text at the given scale (1px gap between glyphs)."""
    if not text:
        return 0
    return len(text) * 6 * scale - scale
